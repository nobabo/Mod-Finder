// Playwright CLI: run-code --filename=tooling/scripts/verify-collections.js
async (page) => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const errors = [];
  const failedRequests = [];
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(() => { localStorage.clear(); localStorage.setItem('modfinder-intro-seen', '1'); document.cookie = 'mf-language=ko; Path=/; SameSite=Lax'; });
  let failRanking = false;
  const now = new Date().toISOString();
  const make = (id, title, tags, downloads, kind = 'mod') => ({ key: `modrinth:minecraft:${id}`, source: 'modrinth', scope: 'minecraft', id, gameId: 'minecraft-java', title, summary: 'Collection verification', rank: 1, author: 'Verification', url: 'https://modrinth.com/mod/sodium', iconUrl: null, updatedAt: null, versions: null, loaders: null, kind, metrics: [{ label: '다운로드', value: downloads }], tags, fetchedAt: now });
  await page.route('**/v1/search?**', async route => {
    const params = new URL(route.request().url()).searchParams;
    const source = params.get('source');
    const category = params.get('category');
    const isRanking = params.get('kind') === 'modpack' && !params.get('query');
    if (isRanking && failRanking) { failedRequests.push(source); await route.fulfill({ status: 502, json: { error: 'test_failure' } }); return; }
    const both = make('qa-both', 'Both tags', ['adventure', 'magic'], 1);
    const adventure = make('qa-adventure', 'Adventure only', ['adventure'], 900);
    const magic = make('qa-magic', 'Magic only', ['magic'], 400);
    const items = isRanking ? Array.from({ length: 20 }, (_, index) => { const rank = Number(params.get('cursor') || 0) + index; return { ...make(`pack-${rank}`, `${source === 'modrinth' ? 'Pack' : 'CF Pack'} ${rank + 1}`, [], 200 - rank * 2 - (source === 'modrinth' ? 0 : 1), 'modpack'), source, key: `${source}:minecraft:pack-${rank}` }; })
      : source !== 'modrinth' ? [] : category === 'modrinth:adventure' ? [adventure, both] : category === 'modrinth:magic' ? [magic, both] : [adventure, magic, both];
    await route.fulfill({ json: { source, status: items.length ? 'success' : 'empty', items, nextCursor: isRanking && !params.get('cursor') ? '20' : null, total: items.length, fetchedAt: now, cached: false, appliedFilters: category ? { category } : {}, unsupportedFilters: [], externalUrl: null, queryForwarded: true, message: '' } });
  });
  const menu = async name => {
    if (name === 'TOP 10') { await page.reload(); await page.locator('.ranking-panel').waitFor(); return; }
    await page.getByRole('button', { name: '설정 메뉴', exact: true }).click();
    await page.getByRole('dialog', { name: '설정 메뉴', exact: true }).getByRole('button', { name, exact: true }).click();
  };
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('modfinder:local:v1')));
  try {
    await page.reload();
    await page.locator('#mod-query').fill('fixture');
    await page.locator('#mod-query').press('Enter');
    await page.waitForFunction(() => document.querySelectorAll('.mod-card').length === 3);
    await page.getByRole('button', { name: 'Both tags 즐겨찾기', exact: true }).click();
    assert(await page.getByRole('button', { name: 'Both tags 즐겨찾기 해제', exact: true }).getAttribute('aria-pressed') === 'true', 'Save state');
    await menu('즐겨찾기');
    await page.getByRole('button', { name: '새 폴더', exact: true }).click();
    await page.getByLabel('폴더명', { exact: true }).fill('마법 모험');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await page.getByRole('button', { name: '전체', exact: true }).click();
    await page.getByRole('button', { name: 'Both tags 폴더로 이동', exact: true }).click();
    await page.getByRole('dialog', { name: '폴더로 이동', exact: true }).getByRole('button', { name: '마법 모험', exact: true }).click();
    await page.getByRole('button', { name: '마법 모험', exact: true }).click();
    assert(await page.locator('.mod-card').count() === 1, 'Folder selection');
    await page.getByRole('button', { name: '폴더 이름 변경', exact: true }).click();
    await page.getByLabel('폴더명', { exact: true }).fill('함께 할 모드');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('modfinder:local:v1')).folders[0].name === '함께 할 모드');
    await page.screenshot({ path: 'output/playwright/favorites-folders-desktop.png' });
    await page.reload();
    await menu('즐겨찾기');
    await page.getByRole('button', { name: '함께 할 모드', exact: true }).click();
    assert(await page.locator('.mod-card').count() === 1, 'Favorites and folder survive reload');
    await page.getByRole('button', { name: '폴더 삭제', exact: true }).click();
    assert(await page.locator('.mod-card').count() === 1, 'Deleting folder preserves favorite');
    await page.getByRole('button', { name: 'Both tags 즐겨찾기 해제', exact: true }).click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('modfinder:local:v1')).favorites.length === 0);
    await menu('모드 둘러보기');
    await page.locator('#mod-query').fill('fixture');
    await page.locator('#mod-query').press('Enter');
    await page.getByRole('button', { name: '검색 필터', exact: true }).click();
    await page.getByRole('button', { name: '장르', exact: true }).click();
    await page.getByRole('button', { name: '모험', exact: true }).click();
    await page.getByRole('button', { name: '마법', exact: true }).click();
    assert(await page.getByRole('button', { name: '모험', exact: true }).getAttribute('aria-pressed') === 'true', 'First selected tag retained');
    assert(await page.getByRole('button', { name: '마법', exact: true }).getAttribute('aria-pressed') === 'true', 'Second tag selected');
    await page.screenshot({ path: 'output/playwright/multiple-tags-desktop.png' });
    await page.getByRole('button', { name: '닫기', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.title-button')].map(item => item.textContent).join('|') === 'Both tags|Adventure only|Magic only');
    await page.locator('#mod-query').press('Enter');
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('modfinder:local:v1')).history[0].categories?.length === 2);
    await menu('TOP 10');
    const anchors = () => page.evaluate(() => ['.search-row', '.hero-brand', '.settings-fab'].map(selector => { const box = document.querySelector(selector).getBoundingClientRect(); return [box.x, box.y, box.width, box.height]; }));
    const withRankings = await anchors();
    await page.locator('.ranking-panel').evaluate(element => element.style.display = 'none');
    assert(JSON.stringify(await anchors()) === JSON.stringify(withRankings), 'Rankings preserve original centered anchors');
    await page.locator('.ranking-panel').evaluate(element => element.style.removeProperty('display'));
    assert((await page.locator('.ranking-panel').boundingBox()).width <= 620, 'Compact home ranking width');
    assert(await page.locator('.ranking-list>li').count() === 10, 'Ten community ranks');
    assert(await page.locator('.ranking-panel time,.ranking-metric').count() === 0, 'No ranking metadata');
    assert(await page.locator('.ranking-list strong').first().textContent() === '선릿 밸리', 'Korean pack name');
    await page.screenshot({ path: 'output/playwright/community-top10-desktop.png' });
    await page.getByRole('button', { name: '다운로드 순위', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.ranked-grid>li').length === 10);
    assert(await page.locator('.ranking-providers').count() === 0, 'No provider switches');
    assert(await page.locator('.ranked-grid .title-button').nth(1).textContent() === 'CF Pack 1', 'Combined order');
    assert(await page.getByRole('button', { name: '이전 페이지', exact: true }).isDisabled(), 'First page');
    await page.getByRole('button', { name: '다음 페이지', exact: true }).click();
    assert(await page.locator('.ranked-grid .rank-number').first().textContent() === '11', 'Second page');
    await page.getByRole('button', { name: '다음 페이지', exact: true }).click();
    assert(await page.locator('.ranked-grid .rank-number').last().textContent() === '30', 'Thirty ranks');
    assert(await page.getByRole('button', { name: '다음 페이지', exact: true }).isDisabled(), 'Last page');
    await page.getByRole('button', { name: '이전 페이지', exact: true }).click();
    await page.getByRole('button', { name: '이전 페이지', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.ranked-grid>li').length === 10);
    await page.screenshot({ path: 'output/playwright/download-top10-desktop.png' });
    failRanking = true;
    await page.getByRole('button', { name: '새로고침', exact: true }).click();
    await page.getByText('순위를 불러오지 못했어요.', { exact: true }).waitFor();
    assert(await page.locator('.ranked-grid>li').count() === 0, 'Failed ranking does not retain stale results');
    failRanking = false;
    await page.getByRole('button', { name: '다시 시도', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.ranked-grid>li').length === 10);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Pack 1 즐겨찾기', exact: true }).click();
    await page.getByRole('navigation', { name: '모바일 메뉴' }).getByRole('button', { name: '즐겨찾기', exact: true }).click();
    assert(await page.locator('.mod-card').count() === 1, 'Mobile favorites navigation');
    await page.getByRole('button', { name: '새 폴더', exact: true }).click();
    await page.getByLabel('폴더명', { exact: true }).fill('모바일 폴더');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await page.getByRole('button', { name: '전체', exact: true }).click();
    await page.getByRole('button', { name: 'Pack 1 폴더로 이동', exact: true }).click();
    await page.getByRole('dialog', { name: '폴더로 이동', exact: true }).getByRole('button', { name: '모바일 폴더', exact: true }).click();
    await page.getByRole('button', { name: '모바일 폴더', exact: true }).click();
    await page.screenshot({ path: 'output/playwright/favorites-folders-mobile.png' });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout does not overflow');
    await page.reload(); await page.locator('.ranking-panel').waitFor();
    await page.getByRole('button', { name: '검색 순위', exact: true }).click();
    await page.screenshot({ path: 'output/playwright/community-top10-mobile.png' });
    await page.locator('.ranking-list button').first().click();
    assert(await page.locator('#mod-query').inputValue() === 'Sunlit Valley', 'Community entries start real modpack searches');
    assert((await stored()).favorites.length === 1, 'Favorite remains saved');
    assert(errors.length === 0, errors.join('\n'));
    return { passed: ['save and unsave', 'folder create, move, rename, delete', 'reload persistence', 'multiple tag selection and match priority', 'history tag persistence', 'community TOP 10 and Korean names', 'combined API TOP 30 and pagination', 'failure and retry', 'mobile favorites and ranking', 'community search navigation'], pageErrors: errors, simulatedFailureRequests: failedRequests.length };
  } finally { await page.unrouteAll(); page.off('pageerror', onError); }
}
